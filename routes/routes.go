package routes

import (
	swaggo "github.com/gofiber/contrib/v3/swaggo"
	"github.com/gofiber/fiber/v3"
	"github.com/omarghandour/test1/controllers"
	_ "github.com/omarghandour/test1/docs" // Swagger docs generated by swag
)

// SetupRoutes registers all application routes
func SetupRoutes(app *fiber.App) {
	// Swagger UI Route
	app.Get("/swagger/*", swaggo.HandlerDefault)

	// Welcome Route
	app.Get("/", func(c fiber.Ctx) error {
		return c.JSON(fiber.Map{
			"message": "Welcome to the Go + Fiber + SQLite CRUD API!",
			"swagger": "http://localhost:8080/swagger/",
			"endpoints": fiber.Map{
				"GET /api/books":        "List all books",
				"GET /api/books/:id":    "Get book by ID",
				"POST /api/books":       "Create a new book",
				"PUT /api/books/:id":    "Update a book by ID",
				"DELETE /api/books/:id": "Delete a book by ID",
			},
		})
	})

	// Books CRUD routes
	api := app.Group("/api/books")
	api.Get("/", controllers.GetBooks)
	api.Get("/:id", controllers.GetBook)
	api.Post("/", controllers.CreateBook)
	api.Put("/:id", controllers.UpdateBook)
	api.Delete("/:id", controllers.DeleteBook)
}
